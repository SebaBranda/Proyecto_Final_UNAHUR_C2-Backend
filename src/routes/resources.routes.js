import { Router } from 'express';
import { usuariosCrud, tecnicosCrud } from '../controllers/usuarios.controller.js';
import { clientesCrud } from '../controllers/clientes.controller.js';
import { iniciarSesion } from '../controllers/auth.controller.js';
import { ubicacionesTecnicos } from '../controllers/ubicaciones.controller.js';
import { autenticar } from '../middleware/auth.middleware.js';
import { autorizarRoles } from '../middleware/authorize.middleware.js';
import { vehiculosController } from '../controllers/vehiculos.controller.js';
import { reclamosController } from '../controllers/reclamos.controller.js';
import { jornadasController } from '../controllers/jornadas.controller.js';

const router = Router();

router.post('/auth/login', iniciarSesion);
router.use(autenticar);
router.get('/usuarios', usuariosCrud.listar);
router.get('/usuarios/:id', usuariosCrud.obtener);
router.post('/usuarios', autorizarRoles(1), usuariosCrud.crear);
router.put('/usuarios/:id', autorizarRoles(1), usuariosCrud.actualizar);
router.patch('/usuarios/:id', autorizarRoles(1), usuariosCrud.actualizar);
router.delete('/usuarios/:id', autorizarRoles(1), usuariosCrud.eliminar);
router.get('/tecnicos', tecnicosCrud.listar);
router.get('/tecnicos/:id', tecnicosCrud.obtener);
router.get('/clientes', clientesCrud.listar);
router.get('/clientes/:id', clientesCrud.obtener);
router.post('/clientes', autorizarRoles(1, 2), clientesCrud.crear);
router.put('/clientes/:id', autorizarRoles(1, 2), clientesCrud.actualizar);
router.patch('/clientes/:id', autorizarRoles(1, 2), clientesCrud.actualizar);
router.delete('/clientes/:id', autorizarRoles(1, 2), clientesCrud.eliminar);
router.get('/vehiculos', vehiculosController.listar);
router.post('/vehiculos', autorizarRoles(1, 2), vehiculosController.crear);
router.delete('/vehiculos/:id', autorizarRoles(1, 2), vehiculosController.eliminar);
router.put('/vehiculos/:id', vehiculosController.actualizar);
router.patch('/vehiculos/:id', vehiculosController.actualizar);
router.patch('/vehiculos/:id/asignacion', autorizarRoles(1, 2), vehiculosController.asignar);
router.patch('/vehiculos/:id/kilometraje', vehiculosController.kilometraje);
router.patch('/vehiculos/:id/control', vehiculosController.control);
router.get('/jornadas', jornadasController.listar);
router.post('/jornadas', jornadasController.crear);
router.delete('/jornadas/:id', autorizarRoles(1, 2), jornadasController.eliminar);
router.patch('/jornadas/:id/finalizar', jornadasController.finalizar);
router.get('/reclamos', reclamosController.listar);
router.post('/reclamos', reclamosController.crear);
router.delete('/reclamos/:id', autorizarRoles(1, 2), reclamosController.eliminar);
router.patch('/reclamos/:id/asignacion', reclamosController.asignar);
router.patch('/reclamos/:id/estado', reclamosController.estado);
router.get('/reclamos/:id/evidencias', reclamosController.evidencias);
router.get('/ubicaciones-tecnicos', ubicacionesTecnicos.listar);
router.patch('/ubicaciones-tecnicos/:tecnicoId', ubicacionesTecnicos.actualizar);

export default router;
